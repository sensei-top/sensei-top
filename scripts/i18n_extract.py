"""Write ``src/sensei_top/locale/sensei_top.pot``: every string the backend
passes to ``_()``, ``ngettext()`` or ``N_()``, the template a ``.po``
translates.

Stdlib ``ast`` finds the calls, so the code is read, never imported or run.
A call is ``_(...)``, ``ngettext(...)`` or ``N_(...)`` by bare name, or the
same name on the module (``i18n._(...)``), anywhere under ``src/sensei_top/``.
``N_()`` marks a display constant to translate later (``i18n.py``, trap 2):
its msgid lands in the template like ``_()``'s, and it may run at import
time, since it translates nothing.

The template is written so that it only changes when a string does:
entries sorted by msgid, ``#:`` references carry the file but no line
number, and the header has no creation date. ``tests/test_i18n.py`` runs
``render_pot`` and fails when the file on disk differs, the same check
every phase that wraps strings relies on.

A call this script cannot extract is an error, not a skip, because a
string it misses is a string no translator ever sees:

* an argument that is not a string literal (a variable, an f-string, a
  ``+`` of two strings) — gettext looks up the *runtime* text, which only
  equals a msgid if the code passes the literal. The one exception is
  ``_(CONSTANT)`` or ``_(CONSTANT[key])`` where ``CONSTANT`` is a name the
  same module binds only to ``N_()`` values, at module level — an ``N_()``
  call, or a dict, list, tuple or set whose every value is one — never
  assigns through (``CONSTANT[key] = ...``, ``+=``, ``del``), and the
  call's own function does not rebind: then the runtime text is an
  extracted msgid. What this cannot see is a change through a method
  (``.update()``, ``.append()``) or a ``match`` capture of the name;
* a positional placeholder (``{}``, ``{0}``) — a translation may need to
  reorder its placeholders, which only names allow;
* braces that do not parse as a format string;
* one msgid given two different plurals, or used both bare and counted;
* a ``_()`` or ``ngettext()`` call that runs at import time — at module
  level, in a class body outside any function, in a decorator or a default
  argument — because no request has set a language yet, so the text would
  be English forever (``sensei_top/i18n.py``, trap 2);
* a bare ``_()``, ``ngettext()`` or ``N_()`` where that name is rebound (an
  assignment, a loop, comprehension or ``with`` target, tuple unpacking, a
  parameter, ``except ... as``) in the scope the call resolves it in — the
  throwaway-variable ``_`` idiom silently turns the call into something
  else. A comprehension's target counts for its enclosing function even
  though Python scopes it apart: the rule is "don't name a throwaway ``_``
  where ``_()`` is used", not a model of Python's scoping. An import of the
  name is the one binding that is fine, and ``sensei_top/i18n.py``'s own
  module-level ``def`` of each, which is the function itself.

Run: ``uv run python scripts/i18n_extract.py`` to rewrite the template,
``--check`` to exit non-zero when it is stale without touching it.
"""

from __future__ import annotations

import argparse
import ast
import string
import sys
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path

import polib

REPO = Path(__file__).resolve().parent.parent
SRC_ROOT = REPO / "src" / "sensei_top"
POT_PATH = SRC_ROOT / "locale" / "sensei_top.pot"

GETTEXT = "_"
NGETTEXT = "ngettext"
NOOP = "N_"
NAMES = (GETTEXT, NGETTEXT, NOOP)
# The module that defines the three: its module-level ``def`` of one is the
# function, not a throwaway rebinding it.
DEFINING_MODULE = "sensei_top/i18n.py"
HEADER = (
    "Sensei Top: the dashboard's prose from the server.\n"
    "Generated by scripts/i18n_extract.py; do not edit by hand."
)
METADATA = {
    "Project-Id-Version": "sensei-top",
    "MIME-Version": "1.0",
    "Content-Type": "text/plain; charset=UTF-8",
    "Content-Transfer-Encoding": "8bit",
}


class ExtractError(Exception):
    """One or more calls the template cannot hold; ``problems`` lists each
    as ``path:line: reason``."""

    def __init__(self, problems: list[str]) -> None:
        super().__init__("\n".join(problems))
        self.problems = problems


@dataclass
class Message:
    msgid: str
    plural: str | None = None
    files: set[str] = field(default_factory=set)
    braces: bool = False


def _called_name(call: ast.Call) -> str | None:
    func = call.func
    if isinstance(func, ast.Name) and func.id in NAMES:
        return func.id
    if (
        isinstance(func, ast.Attribute)
        and func.attr in NAMES
        and isinstance(func.value, ast.Name)
        and func.value.id == "i18n"
    ):
        return func.attr
    return None


def _named_fields(text: str) -> list[str]:
    """The placeholder names in ``text``. Raises ``ValueError`` on a
    positional placeholder or braces that do not parse."""
    names = []
    try:
        fields = list(string.Formatter().parse(text))
    except ValueError as exc:
        raise ValueError(f"{exc} in {text!r}; a literal brace is {{{{ or }}}}") from exc
    for _literal, name, _spec, _conversion in fields:
        if name is None:
            continue
        head = name.split(".")[0].split("[")[0]
        if not head or head.isdigit():
            raise ValueError(f"positional placeholder {{{name}}} in {text!r}; name it")
        names.append(head)
    return names


def _literal(node: ast.expr) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def _n_value(node: ast.expr) -> bool:
    """Whether ``node`` is an ``N_()`` call, or a dict, list, tuple or set
    whose every value is one."""
    if isinstance(node, ast.Call):
        return _called_name(node) == NOOP
    if isinstance(node, ast.Dict):
        return bool(node.values) and all(_n_value(value) for value in node.values)
    if isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        return bool(node.elts) and all(_n_value(element) for element in node.elts)
    return False


def _constant_root(node: ast.expr) -> str | None:
    """``CONSTANT`` in ``CONSTANT`` or ``CONSTANT[key]``: the two shapes an
    ``N_()`` constant may be translated in."""
    if isinstance(node, ast.Subscript):
        node = node.value
    return node.id if isinstance(node, ast.Name) else None


@dataclass
class _Scope:
    """One namespace while walking a file. ``import_time`` is whether code
    in it runs when the module is imported; ``function`` whether it is a
    function body (class bodies are skipped when a name is looked up from a
    nested function, as Python does)."""

    parent: _Scope | None
    import_time: bool
    function: bool
    rebound: dict[str, int] = field(default_factory=dict)
    imported: set[str] = field(default_factory=set)
    calls: list[tuple[ast.Call, str]] = field(default_factory=list)
    # Every name bound here, and how many times; on the module scope, how
    # many of those bindings assign an ``N_()`` value (``n_valued``).
    bound: dict[str, int] = field(default_factory=dict)
    n_valued: dict[str, int] = field(default_factory=dict)

    def _visible(self) -> Iterator[_Scope]:
        """The scopes a bare name in this one resolves through, innermost
        first: itself, enclosing functions, the module."""
        scope: _Scope | None = self
        first = True
        while scope is not None:
            if first or scope.function or scope.parent is None:
                yield scope
            first = False
            scope = scope.parent

    def resolve(self, name: str) -> int | None:
        """The line where ``name`` was rebound in the scope a bare
        reference resolves it in, or ``None`` when that scope imports it
        (or nothing binds it, and the module would fail on its own)."""
        for scope in self._visible():
            if name in scope.rebound:
                return scope.rebound[name]
            if name in scope.imported:
                return None
        return None

    def deferred(self, name: str) -> bool:
        """Whether ``name``, read here, is a module constant every binding
        of which is an ``N_()`` value — so its runtime text is a msgid."""
        for scope in self._visible():
            if scope.parent is None:
                count = scope.bound.get(name, 0)
                return count > 0 and scope.n_valued.get(name, 0) == count
            if name in scope.bound:
                return False
        return False


class _ScopeWalker(ast.NodeVisitor):
    """Collects every gettext call with the scope it runs in."""

    def __init__(self, *, defines_gettext: bool = False) -> None:
        self.module = _Scope(parent=None, import_time=True, function=False)
        self.scope = self.module
        self.scopes = [self.module]
        self.defines_gettext = defines_gettext

    def _enter(self, *, function: bool) -> _Scope:
        scope = _Scope(
            parent=self.scope,
            import_time=False if function else self.scope.import_time,
            function=function,
        )
        self.scopes.append(scope)
        return scope

    def _bind(self, name: str | None, line: int) -> None:
        if name is None:
            return
        self.scope.bound[name] = self.scope.bound.get(name, 0) + 1
        if name in NAMES:
            self.scope.rebound.setdefault(name, line)

    def _visit_in(self, scope: _Scope, nodes: list[ast.AST]) -> None:
        outer, self.scope = self.scope, scope
        for node in nodes:
            self.visit(node)
        self.scope = outer

    def _visit_function(self, node: ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda) -> None:
        # Decorators, defaults and annotations run where the def statement
        # runs; only the body waits for a call.
        args = node.args
        outer: list[ast.AST] = [*args.defaults, *(d for d in args.kw_defaults if d)]
        if not isinstance(node, ast.Lambda):
            outer += node.decorator_list
            outer += [a.annotation for a in self._params(args) if a.annotation]
            if node.returns:
                outer.append(node.returns)
            if self.defines_gettext and self.scope is self.module and node.name in NAMES:
                self.scope.imported.add(node.name)
            else:
                self._bind(node.name, node.lineno)
        for child in outer:
            self.visit(child)
        scope = self._enter(function=True)
        outer_scope, self.scope = self.scope, scope
        for param in self._params(args):
            self._bind(param.arg, param.lineno)
        self.scope = outer_scope
        body = [node.body] if isinstance(node, ast.Lambda) else node.body
        self._visit_in(scope, body)

    @staticmethod
    def _params(args: ast.arguments) -> list[ast.arg]:
        params = [*args.posonlyargs, *args.args, *args.kwonlyargs]
        params += [a for a in (args.vararg, args.kwarg) if a]
        return params

    visit_FunctionDef = _visit_function  # noqa: N815
    visit_AsyncFunctionDef = _visit_function  # noqa: N815
    visit_Lambda = _visit_function  # noqa: N815

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        for child in [*node.decorator_list, *node.bases, *node.keywords]:
            self.visit(child)
        self._bind(node.name, node.lineno)
        self._visit_in(self._enter(function=False), node.body)

    def visit_Name(self, node: ast.Name) -> None:
        if isinstance(node.ctx, (ast.Store, ast.Del)):
            self._bind(node.id, node.lineno)

    def visit_Subscript(self, node: ast.Subscript) -> None:
        # ``W[k] = ...``, ``W[k] += ...`` and ``del W[k]`` change what
        # ``_(W[k])`` looks up, so they count as a binding of the module's
        # ``W``, wherever they run (as ``visit_Global`` does).
        if isinstance(node.ctx, (ast.Store, ast.Del)):
            root: ast.expr = node
            while isinstance(root, (ast.Subscript, ast.Attribute)):
                root = root.value
            if isinstance(root, ast.Name):
                self.module.bound[root.id] = self.module.bound.get(root.id, 0) + 1
        self.generic_visit(node)

    def visit_ExceptHandler(self, node: ast.ExceptHandler) -> None:
        self._bind(node.name, node.lineno)
        self.generic_visit(node)

    def _visit_assign(self, node: ast.Assign | ast.AnnAssign) -> None:
        # Counted beside the bindings ``visit_Name`` counts: a module name
        # is an ``N_()`` constant only when the two counts agree.
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        if self.scope is self.module and node.value is not None and _n_value(node.value):
            for target in targets:
                if isinstance(target, ast.Name):
                    self.module.n_valued[target.id] = self.module.n_valued.get(target.id, 0) + 1
        self.generic_visit(node)

    visit_Assign = _visit_assign  # noqa: N815
    visit_AnnAssign = _visit_assign  # noqa: N815

    def visit_Global(self, node: ast.Global) -> None:
        # A function that assigns a ``global`` rebinds the module's name.
        for name in node.names:
            self.module.bound[name] = self.module.bound.get(name, 0) + 1

    def _visit_import(self, node: ast.Import | ast.ImportFrom) -> None:
        for alias in node.names:
            bound = alias.asname or alias.name.split(".")[0]
            self.scope.bound[bound] = self.scope.bound.get(bound, 0) + 1
            if bound in NAMES:
                self.scope.imported.add(bound)

    visit_Import = _visit_import  # noqa: N815
    visit_ImportFrom = _visit_import  # noqa: N815

    def visit_Call(self, node: ast.Call) -> None:
        name = _called_name(node)
        if name is not None:
            self.scope.calls.append((node, name))
        self.generic_visit(node)


def _calls(path: Path, relative: str) -> tuple[list[tuple[int, str, str | None]], list[str]]:
    """``(line, msgid, plural)`` for every call in one file, and the problems."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    walker = _ScopeWalker(defines_gettext=relative == DEFINING_MODULE)
    walker.visit(tree)
    found: list[tuple[int, str, str | None]] = []
    problems: list[str] = []
    calls = [(node, name, scope) for scope in walker.scopes for node, name in scope.calls]
    for node, name, scope in sorted(calls, key=lambda c: (c[0].lineno, c[0].col_offset)):
        where = f"{relative}:{node.lineno}"
        if scope.import_time and name != NOOP:
            problems.append(
                f"{where}: {name}() runs at import time, before any request sets a "
                "language; call it inside the function that uses the text"
            )
            continue
        rebound = scope.resolve(name) if isinstance(node.func, ast.Name) else None
        if rebound is not None:
            problems.append(
                f"{where}: {name} is rebound at line {rebound} in the scope this call "
                f"uses, so this {name}() is not the translation function; give the "
                "throwaway another name"
            )
            continue
        literal_count = 2 if name == NGETTEXT else 1
        expected_args = 3 if name == NGETTEXT else 1
        if node.keywords or len(node.args) != expected_args:
            problems.append(f"{where}: {name}() takes {expected_args} positional argument(s)")
            continue
        texts = [_literal(arg) for arg in node.args[:literal_count]]
        if name == GETTEXT and texts[0] is None:
            root = _constant_root(node.args[0])
            if root is not None and scope.deferred(root):
                # Its msgids were collected from the N_() calls that bind it.
                continue
        if any(text is None for text in texts):
            problems.append(
                f"{where}: {name}() needs string literals (not a variable, an f-string "
                "or a concatenation) so the msgid can be extracted, or for _() a "
                "module-level N_() constant"
            )
            continue
        msgid = texts[0]
        plural = texts[1] if name == NGETTEXT else None
        assert msgid is not None
        if not msgid:
            problems.append(f"{where}: {name}('') is the catalogue header, not a message")
            continue
        found.append((node.lineno, msgid, plural))
    return found, problems


def extract(src_root: Path = SRC_ROOT) -> list[Message]:
    """Every message under ``src_root``, sorted by msgid. Raises
    ``ExtractError`` naming every call it cannot extract."""
    messages: dict[str, Message] = {}
    problems: list[str] = []
    for path in sorted(src_root.rglob("*.py")):
        relative = path.relative_to(src_root.parent).as_posix()
        found, file_problems = _calls(path, relative)
        problems.extend(file_problems)
        for line, msgid, plural in found:
            where = f"{relative}:{line}"
            try:
                fields = _named_fields(msgid) + _named_fields(plural or "")
            except ValueError as exc:
                problems.append(f"{where}: {exc}")
                continue
            message = messages.setdefault(msgid, Message(msgid, plural))
            if message.plural != plural:
                problems.append(
                    f"{where}: {msgid!r} already has plural {message.plural!r}, "
                    f"not {plural!r}"
                )
                continue
            message.files.add(relative)
            message.braces = message.braces or bool(fields)
    if problems:
        raise ExtractError(problems)
    return [messages[msgid] for msgid in sorted(messages)]


def render_pot(src_root: Path = SRC_ROOT) -> str:
    """The template's full text for ``src_root``."""
    pot = polib.POFile(wrapwidth=78)
    pot.header = HEADER
    pot.metadata = dict(METADATA)
    for message in extract(src_root):
        entry = polib.POEntry(
            msgid=message.msgid,
            occurrences=[(path, "") for path in sorted(message.files)],
            flags=["python-brace-format"] if message.braces else [],
        )
        if message.plural is None:
            entry.msgstr = ""
        else:
            entry.msgid_plural = message.plural
            entry.msgstr_plural = {0: "", 1: ""}
        pot.append(entry)
    return str(pot).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the template is stale; write nothing"
    )
    args = parser.parse_args(argv)
    try:
        text = render_pot()
    except ExtractError as exc:
        for problem in exc.problems:
            print(problem, file=sys.stderr)
        return 1
    current = POT_PATH.read_text(encoding="utf-8") if POT_PATH.is_file() else None
    if args.check:
        if text != current:
            print(f"{POT_PATH.relative_to(REPO)} is stale; run scripts/i18n_extract.py",
                  file=sys.stderr)
            return 1
        return 0
    if text != current:
        POT_PATH.parent.mkdir(parents=True, exist_ok=True)
        POT_PATH.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {POT_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
